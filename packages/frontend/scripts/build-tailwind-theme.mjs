/*
 * Generates dist/tailwind.css — a Tailwind v4 @theme block that registers the
 * --govbb-* tokens under Tailwind's namespaces, so a Tailwind consumer gets
 * `bg-teal-80`, `p-s`, `text-body` from the same tokens the CSS components use.
 *
 * Generated rather than hand-written: a hand-kept copy is how the old
 * @govtech-bb/design package drifted into a second, conflicting source of
 * truth. Every token in tokens.css must be mapped here or listed in SKIPPED,
 * and tailwind-theme.test.js fails the build if a new one is neither.
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS = join(here, '../src/tokens.css');
const OUT = join(here, '../dist/tailwind.css');

/** Tokens with no Tailwind namespace — reachable as var(--govbb-*) instead. */
export const SKIPPED = new Set([
  'border-width-form',
  'opacity-disabled',
  'measure', // a layout cap, not a Tailwind namespace value
]);

/** Font sizes carrying their own line height; the rest use the base. */
const OWN_LINE_HEIGHT = new Set(['display', 'h1', 'h2', 'h3']);

/** `--govbb-<name>` → the Tailwind theme variable it registers as. */
export function themeVar(name) {
  if (SKIPPED.has(name)) return null;
  if (name === 'font-sans') return '--font-sans';
  if (name === 'font-mono') return '--font-mono';
  if (name === 'radius') return '--radius';
  if (name.startsWith('letter-spacing-')) return `--tracking-${name.slice(15)}`;
  if (name.startsWith('shadow-')) return `--${name}`;
  if (name.startsWith('space-')) return `--spacing-${name.slice(6)}`;
  if (name.startsWith('font-size-')) return `--text-${name.slice(10)}`;
  if (name.startsWith('line-height-')) return null; // paired onto --text-* below
  if (name.startsWith('color-')) return `--color-${name.slice(6)}`;
  if (name.startsWith('overlay-')) return `--color-${name}`;
  // Link states: --govbb-link-hover-color → --color-link-hover
  if (name.startsWith('link-')) return `--color-${name.replace(/-color$/, '')}`;
  return `--color-${name}`; // primitive ramp: teal-80, grey-20, white-00, teal-ink
}

function parse(css) {
  return [...css.matchAll(/--govbb-([a-z0-9-]+):\s*([^;]+);/g)].map(
    ([, name, value]) => ({ name, value: value.replace(/\s+/g, ' ').trim() }),
  );
}

export function generate(css) {
  const tokens = parse(css);
  const lines = [];
  const registered = new Set();

  for (const { name } of tokens) {
    const key = themeVar(name);
    if (!key || registered.has(key)) continue;
    registered.add(key);
    lines.push(`  ${key}: var(--govbb-${name});`);
    if (key.startsWith('--text-')) {
      const size = key.slice(7);
      const lh = OWN_LINE_HEIGHT.has(size) ? size : 'base';
      lines.push(`  ${key}--line-height: var(--govbb-line-height-${lh});`);
    }
  }

  return `/* Generated by scripts/build-tailwind-theme.mjs — do not edit.
 *
 * Tailwind v4 consumers: @import "@govtech-bb/frontend/tailwind" after
 * @import "tailwindcss". This registers names only — import
 * "@govtech-bb/frontend/css" as well for the token values and the components,
 * so the consumer keeps control of which cascade layer those land in.
 *
 * \`inline\` keeps Tailwind from wrapping values that are already var()
 * references in a second layer of indirection.
 */
@theme inline {
${lines.join('\n')}
}
`;
}

const out = generate(await readFile(TOKENS, 'utf8'));
await mkdir(dirname(OUT), { recursive: true });
await writeFile(OUT, out);
console.log(`tailwind.css: ${out.split('\n').length} lines`);
